"""Generate docs/FIELD_REFERENCE.generated.md from the deal model — the always-current,
drift-proof listing of every field path + type. The curated CONVENTIONS and rationale live
in docs/FIELD_DICTIONARY.md (hand-maintained); this file is the exhaustive shape, derived from
`model/deal.py` so it can never drift from the schema.

Run after any schema change (P3 hygiene, 2026-06-18):
    .venv/Scripts/python scripts/gen_field_reference.py
CI/pre-commit could assert it is up to date by re-running and diffing.
"""

from __future__ import annotations

import sys
from pathlib import Path
from types import NoneType, UnionType
from typing import Union, get_args, get_origin

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from pydantic import BaseModel  # noqa: E402

from creditpaper.model.core import Fact  # noqa: E402
from creditpaper.model.deal import DealModel  # noqa: E402


def _name(t: object) -> str:
    if t is NoneType:
        return "None"
    return getattr(t, "__name__", str(t))


def _is_fact(ann: object) -> bool:
    origin = get_origin(ann) or ann
    return isinstance(origin, type) and issubclass(origin, Fact)


def _is_model(ann: object) -> bool:
    return isinstance(ann, type) and issubclass(ann, BaseModel) and not issubclass(ann, Fact)


def _fact_label(ann: object) -> str:
    meta = getattr(ann, "__pydantic_generic_metadata__", {}) or {}
    args = meta.get("args") or get_args(ann)
    return f"Fact[{', '.join(_name(a) for a in args)}]" if args else "Fact"


def _scalar_label(ann: object) -> str:
    """Render an annotation identically on every supported Python version.

    `X | None` reports its origin as `typing.Union` on 3.11 but `types.UnionType`
    on 3.12+, so rendering the origin's `__name__` makes this generated file
    Python-version-dependent — and the CI drift gate would then fail on whichever
    matrix leg did not produce the committed copy. Unions are always rendered in
    `A | B` form, which is both stable and the way the annotations are written.
    """
    origin = get_origin(ann)
    if origin is None:
        return _name(ann)
    args = get_args(ann)
    if origin is Union or origin is UnionType:
        return " | ".join(_scalar_label(a) for a in args)
    return f"{_name(origin)}[{', '.join(_scalar_label(a) for a in args)}]" if args else _name(origin)


def _walk(
    model_cls: type[BaseModel], prefix: str, rows: list[tuple[str, str]], stack: tuple[type, ...]
) -> None:
    if model_cls in stack:  # guard (schema is a tree, but be safe)
        rows.append((prefix, f"… (recursive {_name(model_cls)})"))
        return
    for fname, info in model_cls.model_fields.items():
        ann = info.annotation
        path = f"{prefix}.{fname}" if prefix else fname
        origin = get_origin(ann)
        if origin is dict:
            _k, vtype = get_args(ann)
            kp = f"{path}[<key>]"
            if _is_fact(vtype):
                rows.append((kp, _fact_label(vtype)))
            elif _is_model(vtype):
                rows.append((kp, _name(vtype)))
                _walk(vtype, kp, rows, stack + (model_cls,))
            else:
                rows.append((kp, _scalar_label(vtype)))
        elif _is_fact(ann):
            rows.append((path, _fact_label(ann)))
        elif _is_model(ann):
            rows.append((path, _name(ann)))
            _walk(ann, path, rows, stack + (model_cls,))
        else:
            rows.append((path, _scalar_label(ann)))


def render() -> str:
    rows: list[tuple[str, str]] = []
    _walk(DealModel, "", rows, ())
    schema_v = DealModel.model_fields["schema_version"].default
    lines = [
        "# Field Reference (GENERATED — do not edit by hand)",
        "",
        f"Every deal-model field path + type, schema **v{schema_v}**, generated from "
        "`model/deal.py` by `scripts/gen_field_reference.py`. **Do not edit this file** — "
        "re-run the script after any schema change. Curated conventions and rationale live "
        "in `FIELD_DICTIONARY.md`; this is the exhaustive, drift-proof shape.",
        "",
        "| Path | Type |",
        "|---|---|",
    ]
    lines += [f"| `{p}` | `{t}` |" for p, t in rows]
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    out = ROOT / "docs" / "FIELD_REFERENCE.generated.md"
    out.write_text(render(), encoding="utf-8")
    n = render().count("\n| `")
    print(f"wrote {out.relative_to(ROOT)} — {n} field paths")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
